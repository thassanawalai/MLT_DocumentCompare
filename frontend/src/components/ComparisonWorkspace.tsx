import React, { useState, useEffect } from 'react';
import {
  FileText,
  AlertTriangle,
  CheckCircle2,
  Download,
  Printer,
  Copy,
  Check,
  RotateCw,
  Eye,
  SlidersHorizontal,
  ChevronDown,
  Layers,
  Sparkles,
} from 'lucide-react';
import { ComparisonScenario, DiscrepancyItem, FieldItem } from '../types/shipping';
import { COMPARISON_SCENARIOS } from '../services/sampleData';
import { runDocumentComparison } from '../services/comparator';
import { DocumentVisualizer } from './DocumentVisualizer';
import { DiscrepancyInspector } from './DiscrepancyInspector';

interface ComparisonWorkspaceProps {
  initialMode?: 'MAIN' | 'HBL' | 'MBL';
  language: 'th' | 'en';
  onGoToAiCompare?: () => void;
}

export const ComparisonWorkspace: React.FC<ComparisonWorkspaceProps> = ({
  initialMode = 'MAIN',
  language,
  onGoToAiCompare,
}) => {
  const isTh = language === 'th';

  // Available scenarios filtered by mode or all
  const filteredScenarios = COMPARISON_SCENARIOS.filter((s) => {
    if (initialMode === 'HBL') return s.mode === 'HBL' || s.id.includes('hbl');
    if (initialMode === 'MBL') return s.mode === 'MBL';
    return true;
  });

  const [activeScenarioId, setActiveScenarioId] = useState<string>(
    filteredScenarios[0]?.id || COMPARISON_SCENARIOS[0].id
  );

  const activeScenario =
    COMPARISON_SCENARIOS.find((s) => s.id === activeScenarioId) || COMPARISON_SCENARIOS[0];

  // Discrepancy & comparison state
  const [selectedField, setSelectedField] = useState<string | null>(null);
  const [reviewedFields, setReviewedFields] = useState<Set<string>>(new Set());
  const [customNotes, setCustomNotes] = useState<Record<string, string>>({});
  const [filterSeverity, setFilterSeverity] = useState<
    'all' | 'critical' | 'warning' | 'info' | 'mismatch_only'
  >('all');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [copiedReport, setCopiedReport] = useState(false);
  const [viewMode, setViewMode] = useState<'SPLIT' | 'DOCS_ONLY' | 'TABLE_ONLY'>('SPLIT');

  // Comparison Results
  const comparisonResult = React.useMemo(() => {
    return runDocumentComparison(activeScenario.siData, activeScenario.blData);
  }, [activeScenario]);

  // If initialMode changed, pick the matching scenario
  useEffect(() => {
    const match = COMPARISON_SCENARIOS.find((s) => s.mode === initialMode);
    if (match) {
      setActiveScenarioId(match.id);
    }
  }, [initialMode]);

  const toggleReviewed = (fieldKey: string) => {
    setReviewedFields((prev) => {
      const next = new Set(prev);
      if (next.has(fieldKey)) {
        next.delete(fieldKey);
      } else {
        next.add(fieldKey);
      }
      return next;
    });
  };

  const updateNote = (fieldKey: string, note: string) => {
    setCustomNotes((prev) => ({ ...prev, [fieldKey]: note }));
  };

  const criticalCount = comparisonResult.discrepancies.filter(
    (d) => !d.isMatch && d.severity === 'critical'
  ).length;

  const warningCount = comparisonResult.discrepancies.filter(
    (d) => !d.isMatch && d.severity === 'warning'
  ).length;

  const handleCopyReport = () => {
    const lines = [
      `=====================================================`,
      `MLT MARITIME VERIFICATION REPORT - ${activeScenario.title}`,
      `Date: ${new Date().toLocaleDateString()} | Booking: ${activeScenario.siData.booking_no?.value || '-'}`,
      `Shipper: ${activeScenario.shipperCompany} | Carrier: ${activeScenario.carrierCompany}`,
      `Total Checked: ${comparisonResult.totalChecked} | Matched: ${comparisonResult.matchCount} | Diffs: ${comparisonResult.mismatchCount}`,
      `=====================================================`,
      '',
      `[DISCREPANCIES FOUND]:`,
      ...comparisonResult.discrepancies
        .filter((d) => !d.isMatch)
        .map(
          (d, i) =>
            `${i + 1}. [${d.severity.toUpperCase()}] ${d.fieldNameEn} (${d.field})\n` +
            `   - SI Value  : ${d.original_value.value.replace(/\n/g, ' ')}\n` +
            `   - B/L Value : ${d.program_value.value.replace(/\n/g, ' ')}\n` +
            (customNotes[d.field] ? `   - Note: ${customNotes[d.field]}\n` : '')
        ),
      '',
      `Report generated by MLT Document Compare Engine.`,
    ];
    navigator.clipboard.writeText(lines.join('\n'));
    setCopiedReport(true);
    setTimeout(() => setCopiedReport(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-4">
      {/* Top Scenario Control & KPI Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs flex flex-col md:flex-row md:items-center justify-between gap-4">
        {/* Scenario Picker */}
        <div className="flex-1 min-w-0">
          <label className="block text-[11px] font-bold uppercase tracking-wider text-slate-500 mb-1">
            {isTh ? 'เลือกชุดเอกสารเปรียบเทียบ (Scenario):' : 'Select Comparison Scenario:'}
          </label>
          <div className="relative">
            <select
              value={activeScenarioId}
              onChange={(e) => {
                setActiveScenarioId(e.target.value);
                setSelectedField(null);
                setReviewedFields(new Set());
              }}
              className="w-full bg-slate-50 border border-slate-300 hover:border-slate-400 font-semibold text-slate-900 rounded-lg py-2 pl-3 pr-9 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500 transition-all cursor-pointer truncate"
            >
              {COMPARISON_SCENARIOS.map((sc) => (
                <option key={sc.id} value={sc.id}>
                  {sc.mode === 'MBL' ? '[MBL] ' : sc.mode === 'HBL' ? '[HBL] ' : '[MAIN] '}
                  {isTh ? sc.titleTh : sc.title}
                </option>
              ))}
            </select>
          </div>
          <p className="text-xs text-slate-500 mt-1 line-clamp-1">
            {activeScenario.description}
          </p>
        </div>

        {/* View Mode & Actions */}
        <div className="flex flex-wrap items-center gap-2">
          {/* Layout buttons */}
          <div className="bg-slate-100 p-0.5 rounded-lg border border-slate-200 flex text-xs">
            <button
              onClick={() => setViewMode('SPLIT')}
              className={`px-2.5 py-1.5 rounded font-medium transition-colors ${
                viewMode === 'SPLIT'
                  ? 'bg-white text-slate-900 shadow-xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
              title="Split View (Documents & Table)"
            >
              {isTh ? 'แบ่ง 2 ส่วน' : 'Split'}
            </button>
            <button
              onClick={() => setViewMode('DOCS_ONLY')}
              className={`px-2.5 py-1.5 rounded font-medium transition-colors ${
                viewMode === 'DOCS_ONLY'
                  ? 'bg-white text-slate-900 shadow-xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
              title="Documents Only"
            >
              {isTh ? 'เฉพาะเอกสาร' : 'Docs'}
            </button>
            <button
              onClick={() => setViewMode('TABLE_ONLY')}
              className={`px-2.5 py-1.5 rounded font-medium transition-colors ${
                viewMode === 'TABLE_ONLY'
                  ? 'bg-white text-slate-900 shadow-xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
              title="Table Diff Only"
            >
              {isTh ? 'เฉพาะตาราง' : 'Table'}
            </button>
          </div>

          {/* AI Compare Shortcut */}
          {onGoToAiCompare && (
            <button
              onClick={onGoToAiCompare}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-gradient-to-r from-blue-600 to-indigo-600 text-white rounded-lg text-xs font-bold shadow-xs hover:from-blue-700 hover:to-indigo-700 transition-all"
            >
              <Sparkles className="w-3.5 h-3.5" />
              {isTh ? 'AI วิเคราะห์เชิงลึก' : 'AI Analysis'}
            </button>
          )}

          {/* Copy Report */}
          <button
            onClick={handleCopyReport}
            className="inline-flex items-center gap-1 px-3 py-1.5 bg-white border border-slate-200 hover:bg-slate-50 text-slate-700 rounded-lg text-xs font-semibold shadow-xs transition-colors"
          >
            {copiedReport ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700">{isTh ? 'คัดลอกแล้ว' : 'Copied'}</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-500" />
                <span>{isTh ? 'คัดลอกผล' : 'Copy'}</span>
              </>
            )}
          </button>

          {/* Print */}
          <button
            onClick={handlePrint}
            className="inline-flex items-center gap-1 px-3 py-1.5 bg-white border border-slate-200 hover:bg-slate-50 text-slate-700 rounded-lg text-xs font-semibold shadow-xs transition-colors"
            title="Print or Save as PDF"
          >
            <Printer className="w-3.5 h-3.5 text-slate-500" />
            <span>{isTh ? 'พิมพ์ / PDF' : 'Print'}</span>
          </button>
        </div>
      </div>

      {/* KPI Stats Strip */}
      <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
        <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-xs">
          <div className="text-[11px] font-bold text-slate-500 uppercase tracking-wider">
            {isTh ? 'ฟิลด์ทั้งหมด' : 'Total Fields'}
          </div>
          <div className="text-xl font-extrabold text-slate-900 mt-1">
            {comparisonResult.totalChecked}
          </div>
          <div className="text-[10px] text-slate-400 mt-0.5">Maritime Schema</div>
        </div>

        <div className="bg-emerald-50/70 p-3 rounded-xl border border-emerald-200/80 shadow-xs">
          <div className="text-[11px] font-bold text-emerald-700 uppercase tracking-wider flex items-center gap-1">
            <CheckCircle2 className="w-3 h-3 text-emerald-600" />
            {isTh ? 'ข้อมูลตรงกัน' : 'Exact Matches'}
          </div>
          <div className="text-xl font-extrabold text-emerald-800 mt-1">
            {comparisonResult.matchCount}
          </div>
          <div className="text-[10px] text-emerald-600 mt-0.5">
            {Math.round((comparisonResult.matchCount / comparisonResult.totalChecked) * 100)}% accuracy
          </div>
        </div>

        <div className="bg-rose-50/70 p-3 rounded-xl border border-rose-200/80 shadow-xs">
          <div className="text-[11px] font-bold text-rose-700 uppercase tracking-wider flex items-center gap-1">
            <AlertTriangle className="w-3 h-3 text-rose-600" />
            {isTh ? 'จุดต่างวิกฤต' : 'Critical Diffs'}
          </div>
          <div className="text-xl font-extrabold text-rose-800 mt-1">
            {criticalCount}
          </div>
          <div className="text-[10px] text-rose-600 mt-0.5">
            {criticalCount > 0 ? (isTh ? 'ต้องแก้ก่อนออก B/L' : 'Requires carrier amendment') : 'No critical errors'}
          </div>
        </div>

        <div className="bg-amber-50/70 p-3 rounded-xl border border-amber-200/80 shadow-xs">
          <div className="text-[11px] font-bold text-amber-700 uppercase tracking-wider">
            {isTh ? 'คำเตือนทั่วไป' : 'Warnings'}
          </div>
          <div className="text-xl font-extrabold text-amber-800 mt-1">
            {warningCount}
          </div>
          <div className="text-[10px] text-amber-600 mt-0.5">Formatting / unit nuances</div>
        </div>

        <div className="bg-blue-50/70 p-3 rounded-xl border border-blue-200/80 shadow-xs col-span-2 sm:col-span-1">
          <div className="text-[11px] font-bold text-blue-700 uppercase tracking-wider">
            {isTh ? 'ตรวจสอบแล้ว' : 'Reviewed'}
          </div>
          <div className="text-xl font-extrabold text-blue-800 mt-1">
            {reviewedFields.size} / {comparisonResult.mismatchCount}
          </div>
          <div className="text-[10px] text-blue-600 mt-0.5">
            {reviewedFields.size === comparisonResult.mismatchCount && comparisonResult.mismatchCount > 0
              ? (isTh ? 'ครบทุกจุดแล้ว' : 'All reviewed')
              : (isTh ? 'ยังค้างตรวจ' : 'Pending review')}
          </div>
        </div>
      </div>

      {/* Main Workspace: Documents Pane */}
      {(viewMode === 'SPLIT' || viewMode === 'DOCS_ONLY') && (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4 h-[560px]">
          {/* Left: Shipping Instruction (SI) */}
          <DocumentVisualizer
            title={isTh ? 'Shipping Instruction (SI - เอกสารตั้งต้น)' : 'Shipping Instruction (SI - Original)'}
            docType="SI"
            carrierOrShipperName={activeScenario.shipperCompany}
            fields={comparisonResult.normalizedOrig}
            discrepancies={comparisonResult.discrepancies}
            selectedField={selectedField}
            onSelectField={setSelectedField}
            language={language}
          />

          {/* Right: Bill of Lading (B/L Draft) */}
          <DocumentVisualizer
            title={isTh ? 'Bill of Lading Draft (B/L - เอกสารคู่เทียบ)' : 'Bill of Lading Draft (B/L - Draft)'}
            docType="BL"
            carrierOrShipperName={activeScenario.carrierCompany}
            fields={comparisonResult.normalizedProg}
            discrepancies={comparisonResult.discrepancies}
            selectedField={selectedField}
            onSelectField={setSelectedField}
            language={language}
          />
        </div>
      )}

      {/* Discrepancy Inspector Table */}
      {(viewMode === 'SPLIT' || viewMode === 'TABLE_ONLY') && (
        <div className={viewMode === 'SPLIT' ? 'h-[480px]' : 'h-[700px]'}>
          <DiscrepancyInspector
            discrepancies={comparisonResult.discrepancies}
            selectedField={selectedField}
            onSelectField={setSelectedField}
            reviewedFields={reviewedFields}
            onToggleReviewed={toggleReviewed}
            customNotes={customNotes}
            onUpdateNote={updateNote}
            filterSeverity={filterSeverity}
            setFilterSeverity={setFilterSeverity}
            searchQuery={searchQuery}
            setSearchQuery={setSearchQuery}
            language={language}
          />
        </div>
      )}
    </div>
  );
};
